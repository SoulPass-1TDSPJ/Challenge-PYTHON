-- Executar uma unica vez no esquema Oracle da equipe.
-- Nao apaga nem substitui tabelas existentes.
CREATE TABLE SOULPASS_USUARIOS_PY (
    ID_USUARIO VARCHAR2(20 CHAR) PRIMARY KEY,
    NOME VARCHAR2(100 CHAR) NOT NULL,
    EMAIL VARCHAR2(150 CHAR) NOT NULL UNIQUE,
    SENHA VARCHAR2(128 CHAR) NOT NULL,
    CPF VARCHAR2(11 CHAR) NOT NULL UNIQUE,
    QRCODE VARCHAR2(40 CHAR) NOT NULL UNIQUE,
    SALDO NUMBER(12, 2) DEFAULT 0 NOT NULL,
    PONTOS NUMBER(12, 0) DEFAULT 0 NOT NULL,
    CONSTRAINT CK_SOULPASS_SALDO CHECK (SALDO >= 0),
    CONSTRAINT CK_SOULPASS_PONTOS CHECK (PONTOS >= 0)
);

CREATE TABLE SOULPASS_EMBARQUES_PY (
    ID_USUARIO VARCHAR2(20 CHAR) NOT NULL,
    HORARIO NUMBER(19, 6) NOT NULL,
    TARIFA NUMBER(12, 2) NOT NULL,
    CONSTRAINT PK_SOULPASS_EMBARQUES PRIMARY KEY (ID_USUARIO, HORARIO),
    CONSTRAINT FK_SOULPASS_EMBARQUE_USR FOREIGN KEY (ID_USUARIO)
        REFERENCES SOULPASS_USUARIOS_PY(ID_USUARIO) ON DELETE CASCADE,
    CONSTRAINT CK_SOULPASS_TARIFA CHECK (TARIFA > 0)
);
